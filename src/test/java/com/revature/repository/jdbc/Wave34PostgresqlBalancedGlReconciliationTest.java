    @Test
    @Timeout(90)
    void concurrentReplayCommitsOnlyOneBalancedEventAndApprovalCannotBeReused()
            throws Exception {
        requireDisposable();
        try (Fixture f = new Fixture()) {
            f.apply(f.event("captured", 1, "CAPTURED", 100), null, false);
            f.apply(f.event("settled", 2, "SETTLED", 100), null, false);
            Event refund = f.event("refund20", 3, "REFUNDED", 20);
            Approval approval = f.approve(refund);
            ExecutorService pool = Executors.newFixedThreadPool(4);
            try {
                CountDownLatch ready = new CountDownLatch(4);
                CountDownLatch fire = new CountDownLatch(1);
                java.util.List<Future<String>> pending = new java.util.ArrayList<>();
                for (int i = 0; i < 4; i++) {
                    pending.add(pool.submit(() -> {
                        ready.countDown();
                        if (!fire.await(10, TimeUnit.SECONDS))
                            throw new AssertionError("GL concurrency rendezvous timed out");
                        return f.apply(refund, approval, false);
                    }));
                }
                assertTrue(ready.await(10, TimeUnit.SECONDS));
                fire.countDown();
                for (Future<String> p : pending) {
                    assertEquals("refund20", p.get(35, TimeUnit.SECONDS));
                }
            } finally {
                pool.shutdownNow();
            }
            assertEquals(3, f.events());
            assertEquals(6, f.lines());
            assertEquals(220L, f.debits());
            assertEquals(220L, f.credits());
            assertEquals(80L, f.balanceOf("1000"));

            Event different = f.event("refund10", 4, "REFUNDED", 10);
            Approval reused = f.approveBy(different, approval.id,
                    NOW.plusSeconds(300), f.finance);
            assertSqlState("23505", () -> f.apply(different, reused, false));
            assertEquals(3, f.events());
            assertEquals(6, f.lines());

            Event tampered = f.event("refund20", 3, "REFUNDED", 21);
            assertThrows(SecurityException.class, () ->
                    f.apply(tampered, f.approve(tampered), false));
            Event newRefund = f.event("refund10", 4, "REFUNDED", 10);
            f.apply(newRefund, f.approve(newRefund), false);
            assertEquals(4, f.events());
            assertEquals(8, f.lines());
            assertEquals(230L, f.debits());
            assertEquals(230L, f.credits());
            assertEquals(70L, f.balanceOf("1000"));
            f.assertLegacyUntouched();
            f.evidence("concurrent-replay-and-approval-uniqueness");
        }
    }

